from fractions import Fraction as F
from itertools import product
from random import Random
from math import log
from time import monotonic
import json
s=monotonic(); rng=Random(11240757)
# In normalized log x coordinates, each forbidden start is [a/(k*C),a/eta).
def covered(y, intervals): return any(l<=y<h for l,h in intervals)
def witness(lo,hi,iv):
    return next((y for y in [lo,hi]+[h for l,h in iv if lo<=h<=hi] if not covered(y,iv)),None)
windows=0; tight=0
for _ in range(18000):
    k=F(rng.randrange(2,9),rng.randrange(1,2)); R=rng.randrange(0,9); C=F(rng.randrange(1,12)); eta=C/rng.randrange(1,8)
    a=[F(rng.randrange(0,100),rng.randrange(1,100)) for i in range(R)]
    B=k*C/eta; hi=1/k; lo=hi/B**R
    iv=[(v/(k*C),v/eta) for v in a if v>0]
    y=witness(lo,hi,iv); assert y is not None
    # Check original quantified implication via endpoints, including open boundary.
    assert lo<=y<=hi and all(v<=eta*y or v>k*C*y for v in a); windows+=1
    if R:
        # At exact endpoint budget, adjacent intervals cover [lo,hi), never hi.
        iv=[(lo*B**i,lo*B**(i+1)) for i in range(R)]
        assert witness(lo,hi,iv)==hi
        # Smaller J (higher lower endpoint) can be covered by strict overlaps.
        # move left end slightly right of lo but left of raised lo, overlap ratio slightly below B.
        r0=lo*(1+F(1,1000)); step=B*(1-F(1,100000)); smallJlo=lo*(1+F(1,500))
        iv=[(r0*step**i,r0*step**i*B) for i in range(R)]
        assert iv[0][0]<smallJlo and iv[-1][1]>hi and all(iv[i+1][0]<iv[i][1] for i in range(R-1))
        assert witness(smallJlo,hi,iv) is None; tight+=1
# Exact 2-primary finite modules with involutions represented by matrices over Z/m.
# All 2x2 matrices mod 2,4,8, plus scalar involutions mod 2^1..2^12.
inv=0; nonzero_defect=0; quotient_nonzero=0; max_discrep=0
for m in (2,4,8,3,5):
  V=list(product(range(m),repeat=2)); z=(0,0)
  for a,b,c,d in product(range(m),repeat=4):
    if ((a*a+b*c)%m,(a*b+b*d)%m,(c*a+d*c)%m,(c*b+d*d)%m)!=(1,0,0,1):continue
    def T(v):return ((a*v[0]+b*v[1])%m,(c*v[0]+d*v[1])%m)
    plus={v for v in V if T(v)==v}; minus={v for v in V if T(v)==((-v[0])%m,(-v[1])%m)}
    im={((T(v)[0]-v[0])%m,(T(v)[1]-v[1])%m) for v in V}; norm={((T(v)[0]+v[0])%m,(T(v)[1]+v[1])%m) for v in V}
    both=plus&minus; sums={((u[0]+v[0])%m,(u[1]+v[1])%m) for u in plus for v in minus}
    assert len(plus)*len(im)==m*m and len(minus)*len(norm)==m*m
    assert len(sums)*len(both)==len(plus)*len(minus)
    assert len(plus)*len(minus)>=m*m and len(minus)%len(im)==0 and len(plus)%len(norm)==0
    assert len(minus)//len(im)==len(plus)//len(norm)
    assert len(both)*len(sums)>=m*m and len(both)>=m*m//len(sums)
    assert all(((2*v[0])%m,(2*v[1])%m) in sums for v in V)
    if m%2:assert len(sums)==m*m and len(both)==1
    inv+=1; nonzero_defect+=len(minus)>len(im); quotient_nonzero+=len(sums)<m*m;max_discrep=max(max_discrep,len(minus)//len(im))
# Exact rank-one block congruence defect: M generated by (1,1),(0,p^k).
# In basis of M, p^k P = [[p^k,0],[-1,0]]; selected and complementary intersection index p^k.
# For direct sums of such blocks and pure eigenlines, denominator exponent max k, defect length sum k.
blocks=0; strict=0; sharp=0
for _ in range(12000):
    p=rng.choice([2,3,5,7,11]); r=rng.randrange(1,15); t=rng.randrange(1,15)
    ks=[rng.randrange(0,11) for _ in range(min(r,t))]; k=max(ks); det=p**sum(ks)
    # determinant of block intersection basis diag factors p^k (unimodular sign irrelevant)
    assert det<=p**(min(r,t)*k)
    assert (det==p**(min(r,t)*k))==all(v==k for v in ks)
    strict+=det<p**(min(r,t)*k); sharp+=det==p**(min(r,t)*k);blocks+=1
print(json.dumps(dict(exact_windows=windows,exact_sharpness_models=tight,exhaustive_involutions=inv,nonzero_Tate_defect=nonzero_defect,nontrivial_quotient=quotient_nonzero,max_Tate_index=max_discrep,exact_DVR_block_models=blocks,strict_bound=strict,sharp_bound=sharp,elapsed_seconds=monotonic()-s),indent=2))

